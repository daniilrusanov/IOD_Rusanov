export const helpSystem = {
  /**
   * Отримати тему допомоги за ID
   */
  getHelpTopic(id: string): HelpTopic | null {
    return helpTopics[id] || null;
  },

  /**
   * Отримати всі теми допомоги
   */
  getAllTopics(): HelpTopic[] {
    return Object.values(helpTopics);
  },

  /**
   * Пошук тем по ключовим словам
   */
  searchTopics(query: string): HelpTopic[] {
    const q = query.toLowerCase();
    return Object.values(helpTopics).filter(
      (topic) =>
        topic.title.toLowerCase().includes(q) ||
        topic.description.toLowerCase().includes(q) ||
        topic.steps.some((s) => s.toLowerCase().includes(q))
    );
  },

  /**
   * Отримати контекстну допомогу для сторінки
   */
  getContextHelp(page: string): ContextHelp | null {
    return contextHelps[page] || null;
  },

  /**
   * Отримати пов\'язані теми
   */
  getRelatedTopics(topicId: string): HelpTopic[] {
    const topic = helpTopics[topicId];
    if (!topic || !topic.relatedTopics) return [];
    return topic.relatedTopics
      .map((id) => helpTopics[id])
      .filter((t) => t !== undefined);
  },
};

